"""Render the PS5Expweb brand artwork (client package + server GUI).

Deterministic renderer: every shape, glow and gradient is computed, so the
artwork can be regenerated byte-stable from this script whenever the design
changes. Outputs land in ``client/artwork/``:

    icon0.png   512x512    shortcut icon (PS5 home screen)
    pic0.png    3840x2160  package background (overview)
    pic1.png    3840x2160  package background (secondary)
    mark-256.png           same mark for the server GUI window/web dashboard

Design language: near-black navy base, electric cyan/violet accents, a
hexagonal chip with a power bolt, faint dot grid and circuit pins. Run with
``python tools/design_artwork.py`` (requires Pillow).
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "client" / "artwork"

# Palette
BG_TOP = (12, 18, 32)
BG_BOTTOM = (7, 10, 19)
CYAN = (34, 211, 238)
CYAN_DEEP = (0, 149, 190)
VIOLET = (124, 92, 255)
WHITE = (234, 242, 255)
MUTED = (176, 198, 226)
INK = (7, 11, 20)


def load_font(size, bold=True):
    candidates = [
        "C:/Windows/Fonts/bahnschrift.ttf",
        "C:/Windows/Fonts/seguisb.ttf" if bold else "C:/Windows/Fonts/segoeui.ttf",
        "C:/Windows/Fonts/arialbd.ttf" if bold else "C:/Windows/Fonts/arial.ttf",
    ]
    for name in candidates:
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            continue
    return ImageFont.load_default()


def lerp(a, b, t):
    return tuple(round(x + (y - x) * t) for x, y in zip(a, b))


def v_gradient(size, top, bottom):
    w, h = size
    strip = Image.new("RGB", (1, h))
    for y in range(h):
        strip.putpixel((0, y), lerp(top, bottom, y / max(1, h - 1)))
    return strip.resize((w, h))


def radial_glow(layer, center, radius, color, alpha):
    w, h = layer.size
    glow = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(glow)
    cx, cy = center
    d.ellipse((cx - radius, cy - radius, cx + radius, cy + radius),
              fill=color + (alpha,))
    glow = glow.filter(ImageFilter.GaussianBlur(radius // 2))
    layer.alpha_composite(glow)


def dot_grid(draw, box, spacing, color, alpha):
    x0, y0, x1, y1 = box
    for y in range(y0, y1, spacing):
        for x in range(x0, x1, spacing):
            draw.point((x, y), fill=color + (alpha,))


def hexagon_points(cx, cy, radius):
    import math
    pts = []
    for i in range(6):
        angle = math.pi / 2 + i * math.pi / 3  # flat-sided (pointy top/bottom)
        pts.append((cx + radius * math.cos(angle), cy - radius * math.sin(angle)))
    return pts


def text_width(draw, text, font, spacing):
    total = 0
    for ch in text:
        box = draw.textbbox((0, 0), ch, font=font)
        total += (box[2] - box[0]) + spacing
    return total - spacing


def letterspaced_text(draw, xy, text, font, fill, spacing):
    x, y = xy
    for ch in text:
        draw.text((x, y), ch, font=font, fill=fill)
        box = draw.textbbox((0, 0), ch, font=font)
        x += (box[2] - box[0]) + spacing
    return x


def draw_chip_mark(canvas, cx, cy, scale):
    """Hexagonal chip + power bolt + circuit pins. Draws onto an RGBA image."""
    d = ImageDraw.Draw(canvas)
    radius = 150 * scale
    stroke = max(2, round(10 * scale))

    # outer glow
    glow = Image.new("RGBA", canvas.size, (0, 0, 0, 0))
    gd = ImageDraw.Draw(glow)
    gd.polygon(hexagon_points(cx, cy, radius), outline=CYAN + (160,), width=stroke)
    glow = glow.filter(ImageFilter.GaussianBlur(round(14 * scale)))
    canvas.alpha_composite(glow)

    # hexagon body
    d.polygon(hexagon_points(cx, cy, radius), fill=(13, 26, 44, 255))
    d.polygon(hexagon_points(cx, cy, radius), outline=CYAN + (255,), width=round(stroke * 1.2))

    # circuit pins: three uniform strokes protruding from the flat walls,
    # each with a contact pad at the wall and a round node at the tip.
    wall = radius * 0.866
    pin = 34 * scale
    pad = 13 * scale
    for side in (-1, 1):
        for row in (-1, 0, 1):
            color = lerp(CYAN, VIOLET, (row + 1) / 2) + (255,)
            y0 = cy + row * 46 * scale
            x0 = cx + side * (wall - 4 * scale)
            x1 = cx + side * (wall + pin)
            d.line((x0, y0, x1, y0), fill=color, width=max(2, round(10 * scale)))
            d.rounded_rectangle((x0 - pad, y0 - pad, x0 + pad, y0 + pad),
                                radius=4 * scale, fill=color)
            r = 8 * scale
            d.ellipse((x1 - r, y0 - r, x1 + r, y0 + r), fill=color)

    # power bolt (bold zigzag) with glow
    bolt_w = 84 * scale
    top = cy - radius * 0.58
    bottom = cy + radius * 0.62
    mid = cy - radius * 0.02
    left = cx - bolt_w * 0.80
    right = cx + bolt_w * 0.92
    bolt = [
        (cx + bolt_w * 0.30, top),
        (left, mid + 14 * scale),
        (cx - bolt_w * 0.02, mid + 18 * scale),
        (cx - bolt_w * 0.30, bottom),
        (right, cy - radius * 0.06),
        (cx + bolt_w * 0.06, cy - radius * 0.10),
    ]
    bglow = Image.new("RGBA", canvas.size, (0, 0, 0, 0))
    bd = ImageDraw.Draw(bglow)
    bd.polygon(bolt, fill=CYAN + (170,))
    bglow = bglow.filter(ImageFilter.GaussianBlur(round(18 * scale)))
    canvas.alpha_composite(bglow)

    # bolt body: flat white core with a single glow (consistent lighting)
    d.polygon(bolt, fill=WHITE + (255,))


def badge(draw, cx, cy, text, scale=1.0, left=None):
    font = load_font(round(52 * scale))
    tw = text_width(draw, text, font, 0)
    w = tw + 72 * scale
    h = 70 * scale
    if left is not None:
        cx = left + w / 2
    # dark keyline separates the cyan pill from the cyan hexagon stroke
    draw.rounded_rectangle((cx - w / 2 - 7 * scale, cy - h / 2 - 7 * scale,
                            cx + w / 2 + 7 * scale, cy + h / 2 + 7 * scale),
                           radius=h, fill=INK + (255,))
    draw.rounded_rectangle((cx - w / 2, cy - h / 2, cx + w / 2, cy + h / 2),
                           radius=h, fill=CYAN + (255,))
    draw.text((cx - tw / 2, cy - h / 2 + 10 * scale), text,
              font=font, fill=INK + (255,))
    return w


def render_icon0():
    size = 512
    base = v_gradient((size, size), BG_TOP, BG_BOTTOM).convert("RGBA")
    radial_glow(base, (120, 90), 300, CYAN_DEEP, 70)
    radial_glow(base, (430, 440), 280, VIOLET, 60)
    d = ImageDraw.Draw(base)
    dot_grid(d, (0, 0, size, size), 16, WHITE, 6)

    draw_chip_mark(base, size // 2, 232, 1.14)
    badge(d, size // 2, 420, "13.60", scale=1.06)
    return base


def render_mark(size=256):
    base = v_gradient((size, size), BG_TOP, BG_BOTTOM).convert("RGBA")
    radial_glow(base, (size * 0.3, size * 0.25), size // 2, CYAN_DEEP, 70)
    radial_glow(base, (size * 0.8, size * 0.85), size // 2, VIOLET, 60)
    draw_chip_mark(base, size // 2, size // 2, size / 512 * 1.12)
    # subtle rim so the tile edge survives on dark backgrounds
    rim = ImageDraw.Draw(base)
    rim.rounded_rectangle((3, 3, size - 4, size - 4), radius=size // 8,
                          outline=WHITE + (30,), width=max(2, size // 128))
    # rounded-corner mask so the tile reads as a card on any background
    mask = Image.new("L", (size, size), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, size - 1, size - 1),
                                           radius=size // 8, fill=255)
    base.putalpha(mask)
    return base


def render_pic(variant):
    w, h = 3840, 2160
    base = v_gradient((w, h), (9, 14, 25), (6, 9, 17)).convert("RGBA")
    radial_glow(base, (700, 380), 1400, CYAN_DEEP, 54)
    radial_glow(base, (3200, 1900), 1500, VIOLET, 46)
    d = ImageDraw.Draw(base)
    dot_grid(d, (0, 0, w, h), 42, WHITE, 8)

    # ghost hexagon watermark: visible, edge-lit, clear of the lockup
    wm = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    wd = ImageDraw.Draw(wm)
    hx = w * (0.82 if variant == 0 else 0.18)
    wd.polygon(hexagon_points(hx, h * 0.52, 700), outline=WHITE + (55,), width=10)
    wd.polygon(hexagon_points(hx, h * 0.52, 350), outline=CYAN + (40,), width=6)
    base.alpha_composite(wm.filter(ImageFilter.GaussianBlur(2)))
    base.alpha_composite(wm.filter(ImageFilter.GaussianBlur(26)))

    # ---- lockup: icon tile + text block sharing top and bottom edges ----
    font_big = load_font(240)
    font_sub = load_font(72, bold=False)
    font_foot = load_font(58, bold=False)
    probe = ImageDraw.Draw(Image.new("RGBA", (8, 8)))
    word = "RELAPSE"
    sub = "PS5 EXPLOIT HOST   \\u00b7   HARDENED"
    foot = "PATNAWA.GITHUB.IO/PS5EXPWEB/RELAPSE"
    word_w = text_width(probe, word, font_big, 28)

    tile_x = 380 if variant == 0 else w - 380 - 720
    tx = tile_x + 880

    # text block, top-down; the tile is sized to share its top/bottom edges
    y = 0
    word_top = y                       # wordmark cap-top
    bar_y = word_top + 330
    sub_y = bar_y + 110
    pill_cy = sub_y + 72 + 150
    block_h = pill_cy + 58            # pill bottom (incl. keyline)
    top = (h - block_h) // 2

    letterspaced_text(d, (tx, top + word_top), word, font_big, WHITE + (255,), 28)
    for i in range(int(word_w)):
        d.line((tx + i, top + bar_y, tx + i, top + bar_y + 14),
               fill=lerp(CYAN, VIOLET, i / word_w) + (255,))
    letterspaced_text(d, (tx, top + sub_y), sub, font_sub, MUTED + (255,), 10)
    badge(d, 0, top + pill_cy, "FW 13.60", scale=1.25, left=tx)

    base.alpha_composite(render_mark(block_h), (tile_x, top))

    # footer anchors the lower band
    foot_x = 380 if variant == 0 else w - 380 - text_width(probe, foot, font_foot, 8)
    letterspaced_text(d, (foot_x, h - 250), foot, font_foot, (150, 172, 202, 255), 8)
    return base


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    render_icon0().save(OUT / "icon0.png", optimize=True)
    render_mark(256).save(OUT / "mark-256.png", optimize=True)
    render_pic(0).save(OUT / "pic0.png", optimize=True)
    render_pic(1).save(OUT / "pic1.png", optimize=True)
    for name in ("icon0.png", "mark-256.png", "pic0.png", "pic1.png"):
        path = OUT / name
        print(f"{name}: {path.stat().st_size // 1024} KiB")


if __name__ == "__main__":
    main()
